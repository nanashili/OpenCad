// Indexed RGB facts measured in controlled reference palette probes.
// See docs/CLEAN_ROOM.md for the behavior-observation and implementation boundary.
// The lookup and special-index fallback are original OpenCad policy.

pub(crate) fn layer_rgb(index: i16, on_white: bool) -> [u8; 3] {
    let index = usize::from(index.unsigned_abs());
    let index = if (1..=255).contains(&index) { index } else { 7 };
    let color = if on_white {
        ON_WHITE[index]
    } else {
        ON_DARK[index]
    };
    [(color >> 16) as u8, (color >> 8) as u8, color as u8]
}

