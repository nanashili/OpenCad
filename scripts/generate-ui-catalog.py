#!/usr/bin/env python3
"""Generate Rust UI declarations from inert, reviewed repository metadata."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def icon_name(action_id):
    return action_id + '-' + hashlib.sha256(action_id.encode()).hexdigest()[:8] + '.png'


def menu(item):
    children = ',\n'.join(menu(child) for child in item['items'])
    return ('MenuItem { label: ' + quote(item['label']) + ', action: '
            + quote(item['action']) + ', children: &[' + children + '] }')


def main():
    data = json.loads((ROOT / 'assets/ui/catalog.json').read_text())
    if data['schemaVersion'] != 1:
        raise ValueError('Unsupported UI catalog schema')
    lines = [
        '// Generated by scripts/generate-ui-catalog.py from assets/ui/catalog.json.',
        '// Functional UI metadata and original OpenCad artwork; no native macros or code.',
        'use super::shell::{ActionInfo, MenuItem, StatusItem, ToolGroup, ToolItem, ToolbarGroup};',
        'pub(super) static MENUS: &[MenuItem] = &[',
        ',\n'.join(menu(item) for item in data['menus']),
        '];',
        'pub(super) static TOOLBARS: &[ToolbarGroup] = &[',
    ]
    for group in data['toolbars']:
        actions = ','.join(quote(action) for action in group['actions'])
        lines.append('ToolbarGroup { label: ' + quote(group['label']) + ', actions: &[' + actions + '] },')
    lines.extend(['];', 'pub(super) static TOOL_GROUPS: &[ToolGroup] = &['])
    for group in data['toolGroups']:
        lines.append('ToolGroup { label: ' + quote(group['label']) + ', layout: ' + quote(group['layout']) + ', items: &[')
        for item in group['items']:
            actions = ','.join(quote(action) for action in item['actions'])
            lines.append('ToolItem { label: ' + quote(item['label']) + ', visible: ' + str(item['visible']).lower() + ', actions: &[' + actions + '] },')
        lines.append('] },')
    lines.extend(['];', 'pub(super) static STATUS_ITEMS: &[StatusItem] = &['])
    for item in data['statusItems']:
        lines.append('StatusItem { id: ' + quote(item['id']) + ', label: ' + quote(item['label']) + ', off: ' + quote(item['off']) + ', on: ' + quote(item['on']) + ' },')
    lines.extend(['];', 'pub(super) static ACTIONS: &[ActionInfo] = &['])
    for action in sorted(data['actions'], key=lambda item: item['id']):
        path = ROOT / 'assets/icons' / icon_name(action['id'])
        if action['icon'] and not path.is_file():
            raise FileNotFoundError(path)
        image = ('Some(include_bytes!("../../assets/icons/' + path.name + '"))' if action['icon'] else 'None')
        lines.append('ActionInfo { id: ' + quote(action['id']) + ', label: ' + quote(action['label']) + ', help: ' + quote(action['label']) + ', image: ' + image + ' },')
    lines.append('];')
    (ROOT / 'src/desktop/catalog.rs').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
