use opencad::{
    DxfDocument, Editor, Entity, GeometryError, Linetype, LinetypeError, Point3, Polyline2,
    PolylineSegment, SvgError, render_document_svg, render_entities_svg,
};
use std::f64::consts::PI;

fn point(x: f64, y: f64, z: f64) -> Point3 {
    Point3::new(x, y, z).unwrap()
}

fn shape(entity: &Entity) -> &Polyline2 {
    let Entity::Polyline(polyline) = entity else {
        panic!("expected POLYLINE")
    };
    polyline
}

fn near(actual: f64, expected: f64) {
    assert!((actual - expected).abs() < 1e-10, "{actual} != {expected}");
}

fn near_point(actual: Point3, expected: Point3) {
    near(actual.x(), expected.x());
    near(actual.y(), expected.y());
    near(actual.z(), expected.z());
}

fn curved(bulge: f64) -> Polyline2 {
    Polyline2::with_bulges(
        vec![point(0.0, 0.0, 7.0), point(10.0, 0.0, 7.0)],
        vec![bulge, 0.0],
        false,
    )
    .unwrap()
}

// Phase-13 tests reject every nonzero bulge. These independent source-app
// sequences expose the missing signed-curve persistence before new geometry
// or widget code is added. Neither fixture is generated by OpenCad.
#[test]
fn independent_bulged_sequences_retain_native_geometry_and_source_bytes() {
    for source in [
        include_str!("fixtures/polyline-bulges-autocad-input.dxf"),
        include_str!("fixtures/polyline-bulges-autocad-r12.dxf"),
    ] {
        let document = DxfDocument::parse(source).unwrap();
        assert_eq!(document.entities().len(), 8);
        assert_eq!(document.to_dxf(), source);
        let quarter = (PI / 8.0).tan();
        let bulges = [
            vec![quarter, 0.0],
            vec![-quarter, 0.0],
            vec![1.0, 0.0],
            vec![-1.0, 0.0],
            vec![2.0, 0.0],
            vec![0.0, quarter, 0.0, -quarter],
            vec![0.0, 0.0, quarter],
            vec![1.0, 0.0],
        ];
        for (index, entity) in document.entities().iter().enumerate() {
            let polyline = shape(entity);
            assert_eq!(polyline.elevation(), 11.0);
            assert_eq!(polyline.is_closed(), index == 6);
            assert_eq!(polyline.bulges().len(), bulges[index].len());
            for (actual, expected) in polyline.bulges().iter().zip(&bulges[index]) {
                near(*actual, *expected);
            }
        }
        assert_eq!(shape(&document.entities()[5]).segments().count(), 3);
        assert_eq!(shape(&document.entities()[7]).length().unwrap(), 0.0);
    }
}

// LINE/ARC tests do not exercise signed traversal, major bulges, outgoing
// vertex ownership, reversal, inactive final values, or degenerate bulges.
#[test]
fn signed_bulges_have_analytic_geometry_and_atomic_vertex_updates() {
    for (bulge, midpoint) in [(1.0, point(5.0, -5.0, 7.0)), (-1.0, point(5.0, 5.0, 7.0))] {
        let polyline = curved(bulge);
        let segment = polyline.segments().next().unwrap().unwrap();
        near(segment.length().unwrap(), 5.0 * PI);
        near_point(
            segment.point_at_fraction(0.0).unwrap(),
            point(0.0, 0.0, 7.0),
        );
        near_point(segment.point_at_fraction(0.5).unwrap(), midpoint);
        near_point(
            segment.point_at_fraction(1.0).unwrap(),
            point(10.0, 0.0, 7.0),
        );
        assert!(segment.point_at_fraction(f64::NAN).is_err());
    }
    let quarter = curved((PI / 8.0).tan());
    near(quarter.length().unwrap(), 50.0_f64.sqrt() * PI / 2.0);
    near_point(
        quarter
            .segments()
            .next()
            .unwrap()
            .unwrap()
            .point_at_fraction(0.5)
            .unwrap(),
        point(5.0, 5.0 - 50.0_f64.sqrt(), 7.0),
    );
    let major = curved(2.0);
    near(major.length().unwrap(), 6.25 * 4.0 * 2.0_f64.atan());
    near_point(
        major
            .segments()
            .next()
            .unwrap()
            .unwrap()
            .point_at_fraction(0.5)
            .unwrap(),
        point(5.0, -10.0, 7.0),
    );
    for closed in [false, true] {
        let mut polyline = Polyline2::with_bulges(
            vec![
                point(0.0, 0.0, 7.0),
                point(10.0, 0.0, 7.0),
                point(10.0, 10.0, 7.0),
            ],
            vec![1.0, -0.5, 2.0],
            closed,
        )
        .unwrap();
        let original = polyline.clone();
        let length = polyline.length().unwrap();
        polyline.reverse();
        assert_eq!(polyline.bulges(), &[0.5, -1.0, -2.0]);
        near(polyline.length().unwrap(), length);
        polyline.reverse();
        assert_eq!(polyline, original);
        for error in [
            polyline.set_bulges(vec![0.0]),
            polyline.set_bulges(vec![0.0, f64::NAN, 0.0]),
            polyline.set_bulge(3, 1.0),
            polyline.set_bulge(0, f64::INFINITY),
        ] {
            assert!(error.is_err());
        }
        assert_eq!(polyline, original);
        let Entity::Polyline(translated) = Entity::Polyline(polyline.clone())
            .translated(2.0, 3.0, 4.0)
            .unwrap()
        else {
            unreachable!()
        };
        assert_eq!(translated.bulges(), polyline.bulges());
        assert_eq!(translated.elevation(), 11.0);
        polyline
            .set_vertices(vec![point(0.0, 0.0, 7.0), point(10.0, 0.0, 7.0)])
            .unwrap();
        assert_eq!(polyline.bulges(), &[1.0, -0.5]);
    }
    let coincident =
        Polyline2::with_bulges(vec![point(5.0, 5.0, 7.0); 2], vec![1.0, 0.0], false).unwrap();
    assert!(matches!(
        coincident.segments().next().unwrap().unwrap(),
        PolylineSegment::Line(_)
    ));
    assert_eq!(coincident.length().unwrap(), 0.0);
    for extreme in [1e308, 1e-308] {
        assert_eq!(
            curved(extreme).length(),
            Err(GeometryError::UnrepresentableBulge)
        );
        assert!(render_entities_svg(&[Entity::Polyline(curved(extreme))]).is_err());
    }
}

const SOURCE: &str = "0\nSECTION\n2\nENTITIES\n0\nPOLYLINE\n5\nA0\n8\n0\n10\n0\n20\n0\n30\n7\n70\n1\n0\nVERTEX\n5\nA1\n8\n0\n10\n0.00\n20\n0\n42\n1.000\n0\nVERTEX\n5\nA2\n8\n0\n10\n10\n20\n0\n0\nVERTEX\n5\nA3\n8\n0\n10\n10\n20\n10\n42\n-1.000\n0\nSEQEND\n5\nA4\n8\n0\n0\nENDSEC\n0\nEOF\n";

// Curved-source edits need both group42 insertion and overlapping child
// deletion; straight-source history cannot catch bulge loss on copy/reverse.
#[test]
fn bulge_edits_preserve_record_spelling_handles_and_history() {
    let mut document = DxfDocument::parse(SOURCE).unwrap();
    assert_eq!(document.to_dxf(), SOURCE);
    let mut polyline = shape(&document.entities()[0]).clone();
    polyline.set_bulge(0, 0.5).unwrap();
    document
        .replace_entity(0, Entity::Polyline(polyline.clone()))
        .unwrap();
    assert_eq!(
        document.to_dxf(),
        SOURCE.replacen("42\n1.000\n", "42\n0.5\n", 1)
    );
    polyline.set_bulge(1, 2.0).unwrap();
    polyline
        .set_vertices(polyline.vertices()[..2].to_vec())
        .unwrap();
    document
        .replace_entity(0, Entity::Polyline(polyline.clone()))
        .unwrap();
    let saved = document.to_dxf();
    assert!(!saved.contains("5\nA3\n"));
    assert!(saved.contains("42\n2\n0\nSEQEND\n5\nA4\n"));
    assert_eq!(
        shape(&DxfDocument::parse(&saved).unwrap().entities()[0]),
        &polyline
    );
    let mut vertices = polyline.vertices().to_vec();
    vertices.push(point(2.0, 4.0, 7.0));
    vertices.push(point(4.0, 8.0, 7.0));
    polyline.set_vertices(vertices).unwrap();
    polyline.set_bulge(2, -2.0).unwrap();
    polyline.set_bulge(3, 0.25).unwrap();
    document
        .replace_entity(0, Entity::Polyline(polyline))
        .unwrap();
    let mut editor = Editor::new(document);
    editor.select(vec![0]);
    let before = editor.to_dxf();
    editor.translate_selection(2.0, 3.0, 4.0, false).unwrap();
    assert_eq!(
        shape(&editor.entities()[0]).bulges(),
        &[0.5, 2.0, -2.0, 0.25]
    );
    assert!(editor.undo());
    assert_eq!(editor.to_dxf(), before);
    assert!(editor.redo());
    editor.translate_selection(10.0, 0.0, 0.0, true).unwrap();
    assert_eq!(
        shape(&editor.entities()[1]).bulges(),
        &[0.5, 2.0, -2.0, 0.25]
    );
    let saved = editor.to_dxf();
    assert_eq!(
        DxfDocument::parse(&saved).unwrap().entities(),
        editor.entities()
    );
    assert!(DxfDocument::parse(&SOURCE.replacen("42\n1.000\n", "42\nNaN\n", 1)).is_err());
    assert!(DxfDocument::parse(&SOURCE.replacen("42\n1.000\n", "42\n1\n42\n2\n", 1)).is_err());
}

// Endpoint-only bounds clip bulges; CCW-only dash expansion starts negative
// bulges at the wrong endpoint. Check the exported geometry and dot origin.
#[test]
fn svg_bounds_arc_flags_and_clockwise_patterns_follow_curved_segments() {
    let positive = render_entities_svg(&[Entity::Polyline(curved(1.0))]).unwrap();
    assert!(positive.contains("viewBox=\"0 0 30 25\""));
    assert!(positive.contains(" A 5 5 0 0 0 20 10"));
    let negative = render_entities_svg(&[Entity::Polyline(curved(-1.0))]).unwrap();
    assert!(negative.contains(" A 5 5 0 0 1 20 15"));
    let major = render_entities_svg(&[Entity::Polyline(curved(2.0))]).unwrap();
    assert!(major.contains("viewBox=\"0 0 32.5 30\""));
    assert!(major.contains(" A 6.25 6.25 0 1 0 "));
    let mut document = DxfDocument::default();
    document.push(Entity::Polyline(curved(-1.0)));
    document
        .add_linetype(Linetype::new("DOTDASH", vec![0.0, -1.0, 2.0, -1.0]).unwrap())
        .unwrap();
    document.set_entity_linetype(0, "DOTDASH").unwrap();
    let patterned = render_document_svg(&document).unwrap();
    let first_dot = patterned.split("<circle ").nth(1).unwrap();
    assert!(first_dot.starts_with("cx=\"10\" cy=\"15\""), "{patterned}");
    document
        .add_linetype(Linetype::new("DENSE", vec![0.0001, -0.0001]).unwrap())
        .unwrap();
    document.set_entity_linetype(0, "DENSE").unwrap();
    assert_eq!(
        render_document_svg(&document),
        Err(SvgError::Linetype(LinetypeError::TooDense))
    );
}

// Creation constructions need ordered tangents and a through-point solution;
// DXF import tests alone only check already supplied bulges.
#[test]
fn tangent_arc_construction_preserves_signed_minor_major_and_straight_solutions() {
    let start = point(0.0, 0.0, 7.0);
    let quarter = (PI / 8.0).tan();
    let major = (3.0 * PI / 8.0).tan();
    for (end, bulge, midpoint, tangent) in [
        (
            point(10.0, 10.0, 7.0),
            quarter,
            point(50.0_f64.sqrt(), 10.0 - 50.0_f64.sqrt(), 7.0),
            (0.0, 1.0),
        ),
        (
            point(10.0, -10.0, 7.0),
            -quarter,
            point(50.0_f64.sqrt(), -10.0 + 50.0_f64.sqrt(), 7.0),
            (0.0, -1.0),
        ),
        (
            point(-10.0, 10.0, 7.0),
            major,
            point(50.0_f64.sqrt(), 10.0 + 50.0_f64.sqrt(), 7.0),
            (0.0, -1.0),
        ),
        (
            point(-10.0, -10.0, 7.0),
            -major,
            point(50.0_f64.sqrt(), -10.0 - 50.0_f64.sqrt(), 7.0),
            (0.0, 1.0),
        ),
        (
            point(0.0, 20.0, 7.0),
            1.0,
            point(10.0, 10.0, 7.0),
            (-1.0, 0.0),
        ),
    ] {
        let segment = PolylineSegment::arc_from_tangent(start, end, (5.0, 0.0)).unwrap();
        near(segment.bulge(), bulge);
        near_point(segment.point_at_fraction(0.0).unwrap(), start);
        near_point(segment.point_at_fraction(1.0).unwrap(), end);
        near_point(segment.point_at_fraction(0.5).unwrap(), midpoint);
        let actual = segment.end_tangent_xy().unwrap();
        near(actual.0, tangent.0);
        near(actual.1, tangent.1);
        let restored =
            Polyline2::with_bulges(vec![start, end], vec![segment.bulge(), 0.0], false).unwrap();
        near(restored.length().unwrap(), segment.length().unwrap());
        let continued = PolylineSegment::arc_from_tangent(end, point(20.0, 20.0, 7.0), actual);
        // All except the collinear backward chord admit a finite continuation.
        if end == point(0.0, 20.0, 7.0) {
            assert!(continued.is_err());
        } else {
            let continued = continued.unwrap();
            let ahead = continued.point_at_fraction(1e-7).unwrap();
            let dx = ahead.x() - end.x();
            let dy = ahead.y() - end.y();
            let length = dx.hypot(dy);
            assert!((dx / length - actual.0).abs() < 1e-6);
            assert!((dy / length - actual.1).abs() < 1e-6);
        }
    }
    let straight =
        PolylineSegment::arc_from_tangent(start, point(10.0, 0.0, 7.0), (1.0, 0.0)).unwrap();
    assert!(matches!(straight, PolylineSegment::Line(_)));
    assert_eq!(straight.bulge(), 0.0);
    assert_eq!(straight.end_tangent_xy().unwrap(), (1.0, 0.0));
    let semicircle_end = point(0.0, 20.0, 7.0);
    let semicircle = PolylineSegment::arc_from_tangent(start, semicircle_end, (1.0, 0.0)).unwrap();
    assert!(matches!(
        PolylineSegment::arc_from_tangent(
            semicircle_end,
            point(-10.0, 20.0, 7.0),
            semicircle.end_tangent_xy().unwrap()
        )
        .unwrap(),
        PolylineSegment::Line(_)
    ));
    for magnitude in [1e-320, 1.0, f64::MAX] {
        let diagonal =
            PolylineSegment::arc_from_tangent(start, point(0.0, 20.0, 7.0), (magnitude, magnitude))
                .unwrap();
        near(diagonal.bulge(), quarter);
    }
}

#[test]
fn three_point_arcs_choose_the_locus_through_the_middle_pick_at_varied_scales() {
    let quarter = (PI / 8.0).tan();
    let major = (3.0 * PI / 8.0).tan();
    for scale in [1e-150, 1.0, 1e150] {
        let p = |x, y| point(x * scale, y * scale, 7.0);
        for (through, end, bulge, fraction) in [
            (p(0.0, 1.0), p(-1.0, 0.0), 1.0, 0.5),
            (p(0.0, -1.0), p(-1.0, 0.0), -1.0, 0.5),
            (p(-1.0, 0.0), p(0.0, -1.0), major, 2.0 / 3.0),
            (p(-1.0, 0.0), p(0.0, 1.0), -major, 2.0 / 3.0),
            (p((PI / 6.0).cos(), 0.5), p(0.0, 1.0), quarter, 1.0 / 3.0),
        ] {
            let start = p(1.0, 0.0);
            let segment = PolylineSegment::arc_through(start, through, end).unwrap();
            near(segment.bulge(), bulge);
            let actual = segment.point_at_fraction(fraction).unwrap();
            near(actual.x() / scale, through.x() / scale);
            near(actual.y() / scale, through.y() / scale);
            assert_eq!(actual.z(), 7.0);
            near(segment.length().unwrap() / scale, 4.0 * bulge.abs().atan());
            let reversed = PolylineSegment::arc_through(end, through, start).unwrap();
            near(reversed.bulge(), -bulge);
            near(
                reversed.length().unwrap() / scale,
                segment.length().unwrap() / scale,
            );
        }
    }
}

#[test]
fn arc_creation_rejects_incomplete_degenerate_nonplanar_and_unrepresentable_geometry() {
    let start = point(0.0, 0.0, 7.0);
    let end = point(10.0, 0.0, 7.0);
    for through in [
        start,
        end,
        point(5.0, 0.0, 7.0),
        point(5.0, 1e-16, 7.0),
        point(5.0, 1.0, 8.0),
    ] {
        assert!(PolylineSegment::arc_through(start, through, end).is_err());
    }
    assert!(PolylineSegment::arc_through(start, point(5.0, 2.0, 7.0), start).is_err());
    for tangent in [
        (0.0, 0.0),
        (f64::NAN, 1.0),
        (f64::INFINITY, 0.0),
        (-1.0, 0.0),
    ] {
        assert!(PolylineSegment::arc_from_tangent(start, end, tangent).is_err());
    }
    assert!(PolylineSegment::arc_from_tangent(start, start, (1.0, 0.0)).is_err());
    assert!(PolylineSegment::arc_from_tangent(start, point(1.0, 1.0, 8.0), (1.0, 0.0)).is_err());
    assert!(
        PolylineSegment::arc_from_tangent(start, point(-10.0, 1e-300, 7.0), (1.0, 0.0)).is_err()
    );
    let huge = point(-f64::MAX, 0.0, 7.0);
    assert!(
        PolylineSegment::arc_from_tangent(huge, point(f64::MAX, 1.0, 7.0), (1.0, 0.0)).is_err()
    );
    assert!(
        PolylineSegment::arc_through(huge, point(0.0, 1.0, 7.0), point(f64::MAX, 0.0, 7.0))
            .is_err()
    );
}

// Included-angle construction must retain traversal, independent of tangent
// inference or a through-point solver, and center construction must rotate the radius.
#[test]
fn signed_sweep_and_center_arcs_match_analytic_circles_at_varied_scales() {
    let root_half = 0.5_f64.sqrt();
    for scale in [1e-150, 1.0, 1e150] {
        let p = |x, y| point((3.0 + x) * scale, (-2.0 + y) * scale, 7.0);
        let center = p(0.0, 0.0);
        let start = p(1.0, 0.0);
        for (sweep, end, middle) in [
            (PI / 2.0, p(0.0, 1.0), p(root_half, root_half)),
            (-PI / 2.0, p(0.0, -1.0), p(root_half, -root_half)),
            (PI, p(-1.0, 0.0), p(0.0, 1.0)),
            (-PI, p(-1.0, 0.0), p(0.0, -1.0)),
            (3.0 * PI / 2.0, p(0.0, -1.0), p(-root_half, root_half)),
            (-3.0 * PI / 2.0, p(0.0, 1.0), p(-root_half, -root_half)),
        ] {
            for segment in [
                PolylineSegment::arc_from_sweep(start, end, sweep).unwrap(),
                PolylineSegment::arc_about(start, center, sweep).unwrap(),
            ] {
                near(segment.bulge(), (sweep / 4.0).tan());
                near(segment.length().unwrap() / scale, sweep.abs());
                for (fraction, expected) in [(0.0, start), (0.5, middle), (1.0, end)] {
                    let actual = segment.point_at_fraction(fraction).unwrap();
                    near(actual.x() / scale, expected.x() / scale);
                    near(actual.y() / scale, expected.y() / scale);
                    assert_eq!(actual.z(), 7.0);
                }
                let PolylineSegment::Arc { arc, clockwise } = segment else {
                    panic!("nonzero sweep must be an arc");
                };
                assert_eq!(clockwise, sweep < 0.0);
                near(arc.center().x() / scale, center.x() / scale);
                near(arc.center().y() / scale, center.y() / scale);
                near(arc.radius() / scale, 1.0);
            }
        }
    }
}

#[test]
fn signed_sweep_and_center_arcs_reject_invalid_and_unrepresentable_constructions() {
    use std::f64::consts::TAU;
    let start = point(1.0, 0.0, 7.0);
    let end = point(0.0, 1.0, 7.0);
    let center = point(0.0, 0.0, 7.0);
    for sweep in [0.0, -0.0, TAU, -TAU, 3.0 * PI, -3.0 * PI] {
        assert_eq!(
            PolylineSegment::arc_from_sweep(start, end, sweep),
            Err(GeometryError::InvalidArcSweep)
        );
        assert_eq!(
            PolylineSegment::arc_about(start, center, sweep),
            Err(GeometryError::InvalidArcSweep)
        );
    }
    for sweep in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert_eq!(
            PolylineSegment::arc_from_sweep(start, end, sweep),
            Err(GeometryError::NonFiniteAngle)
        );
        assert_eq!(
            PolylineSegment::arc_about(start, center, sweep),
            Err(GeometryError::NonFiniteAngle)
        );
    }
    assert_eq!(
        PolylineSegment::arc_from_sweep(start, start, PI),
        Err(GeometryError::DegenerateCurve)
    );
    assert_eq!(
        PolylineSegment::arc_about(start, start, PI),
        Err(GeometryError::DegenerateCurve)
    );
    let other_plane = point(0.0, 1.0, 8.0);
    assert_eq!(
        PolylineSegment::arc_from_sweep(start, other_plane, PI),
        Err(GeometryError::NonPlanarPolyline)
    );
    assert_eq!(
        PolylineSegment::arc_about(start, other_plane, PI),
        Err(GeometryError::NonPlanarPolyline)
    );
    assert!(PolylineSegment::arc_from_sweep(start, end, 1e-320).is_err());
    assert!(PolylineSegment::arc_about(start, center, f64::from_bits(1)).is_err());
    let huge = point(f64::MAX, 0.0, 7.0);
    assert!(PolylineSegment::arc_from_sweep(start, huge, 1e-300).is_err());
    assert!(PolylineSegment::arc_about(start, huge, PI).is_err());
}
